// Pruebas sobre una instancia local aislada. No usa perfiles del navegador del usuario.
import fs from 'node:fs/promises'
import path from 'node:path'
import { createRequire } from 'node:module'
const require = createRequire(import.meta.url)
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const base = process.env.PIZZA_TEST_URL || 'http://127.0.0.1:5182'
if (!/^http:\/\/(127\.0\.0\.1|localhost):\d+$/.test(base)) throw new Error('Solo se permiten pruebas en un servidor local.')
const output = path.resolve('.tmp/ui-checks')
await fs.mkdir(output, { recursive: true })
const browser = await chromium.launch({ executablePath: process.env.PIZZA_TEST_BROWSER, headless: true })
const checks = []
const failures = []
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } })
page.on('pageerror', (error) => failures.push(error.message))
await page.route('**/*', (route) => new URL(route.request().url()).origin === base ? route.continue() : route.abort())
function check(name, result) { if (!result) throw new Error(name); checks.push(name) }
try {
  await page.goto(base)
  await page.getByLabel('Correo electrónico', { exact: true }).fill('pizzapronto@gmail.com')
  await page.getByLabel('Contraseña', { exact: true }).fill(process.env.PIZZA_TEST_PASSWORD)
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await page.getByRole('button', { name: 'Panel admin', exact: true }).click()
  await page.getByRole('button', { name: 'Recetas', exact: true }).click()
  await page.getByRole('heading', { name: 'Recetas de consumo', exact: true }).waitFor()
  await page.getByLabel(/^Producto o ingrediente/).selectOption('menu:pan-ajo:unico')
  await page.getByRole('button', { name: 'Guardar receta', exact: true }).waitFor()
  await page.screenshot({ path: path.join(output, 'desktop-recipes.png'), fullPage: true })
  check('Editor de recetas visible en escritorio', true)
  await page.getByRole('button', { name: 'Reportes', exact: true }).click()
  await page.getByRole('heading', { name: 'Pedidos y cobros por periodo' }).waitFor()
  await page.getByLabel('Desde', { exact: true }).fill('2000-01-01')
  await page.getByLabel('Hasta', { exact: true }).fill('2000-01-02')
  await page.getByRole('button', { name: 'Consultar', exact: true }).click()
  await page.getByText('Sin operaciones para estos filtros.', { exact: true }).waitFor()
  check('Reporte vacío comprensible', true)
  await page.getByRole('button', { name: 'Cerrar sesión', exact: true }).click()
  await page.getByRole('button', { name: 'Continuar como invitado', exact: true }).click()
  await page.getByLabel('Nombre completo', { exact: true }).fill('Prueba de interfaz')
  await page.getByLabel('Número de teléfono', { exact: true }).fill('999111222')
  await page.getByRole('button', { name: 'Retiro local', exact: true }).click()
  await page.getByRole('button', { name: 'Ver la carta', exact: true }).click()
  await page.setViewportSize({ width: 375, height: 812 })
  await page.getByRole('searchbox', { name: 'Buscar en la carta', exact: true }).fill('Pan al Ajo')
  await page.getByRole('button', { name: /^Agregar Pan al Ajo \(/ }).click()
  check('Carta móvil sin desbordamiento horizontal', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1))
  await page.screenshot({ path: path.join(output, 'mobile-menu.png'), fullPage: true })
  const trigger = page.getByRole('button', { name: /^Abrir pedido,/ })
  await trigger.click()
  const dialog = page.getByRole('dialog', { name: 'El pedido.' })
  await dialog.waitFor()
  await page.waitForFunction(() => document.activeElement?.closest('[role="dialog"]') !== null)
  check('Foco inicial dentro del carrito', true)
  await page.keyboard.press('Shift+Tab')
  check('Shift Tab conserva el foco dentro del carrito', await page.evaluate(() => !!document.activeElement?.closest('[role="dialog"]')))
  await page.keyboard.press('Tab')
  check('Tab conserva el foco dentro del carrito', await page.evaluate(() => !!document.activeElement?.closest('[role="dialog"]')))
  await page.keyboard.press('Escape')
  await dialog.waitFor({ state: 'hidden' })
  check('Escape cierra y devuelve foco al botón', await trigger.evaluate((button) => button === document.activeElement))
  await trigger.click()
  await page.getByRole('button', { name: 'Continuar con el pedido', exact: true }).click()
  await page.getByLabel('¿Con cuánto pagarás?', { exact: true }).fill('100')
  await page.screenshot({ path: path.join(output, 'mobile-checkout.png'), fullPage: true })
  await page.getByRole('button', { name: 'Confirmar pedido', exact: true }).click()
  await page.getByRole('heading', { name: '¡Gracias, Prueba de interfaz!' }).waitFor()
  check('Pedido móvil completo con CSRF activo', true)
  check('Sin errores de JavaScript', failures.length === 0)
  await page.screenshot({ path: path.join(output, 'mobile-confirmation.png'), fullPage: true })
  console.log(JSON.stringify({ checks, failures }, null, 2))
  await fs.writeFile(path.join(output, 'results.json'), JSON.stringify({ checks, failures }, null, 2))
} catch (error) {
  await page.screenshot({ path: path.join(output, 'failure.png'), fullPage: true })
  console.error(error)
  process.exitCode = 1
} finally { await browser.close() }
